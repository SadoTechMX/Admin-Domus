#!/usr/bin/env python3
"""Deterministic native UI/bundles. Does not upload, deploy, or access Sheets."""
import hashlib
import json
import pathlib
import re
import sys

ROOT=pathlib.Path(__file__).resolve().parents[1]
MODULES=['Config','Data','Schema','Auth','Idempotency','Accounts','Payments','POS','Access','KDS','Inventory','Events','Operations','Api']
def build(check=False):
    source={name:(ROOT/f'google-apps-script/{name}.gs').read_text() for name in MODULES}
    digest=hashlib.sha256(''.join(source.values()).encode()).hexdigest()
    build_info={'id':'repair-qa-20261030','sourceSha256':digest,'schema':'DOMUS-DB-v1.1-plus-recovery-journal'}
    generated={}
    prefix='// GENERATED by scripts/build_release.py. Edit source modules, then rebuild.\n'
    generated['google-apps-script/Build.gs']=prefix+'const BACKEND_BUILD = Object.freeze('+json.dumps(build_info)+');\n'
    for env in ['PRODUCTION','STAGING']:
        bundle=prefix+'const BUNDLE_TARGET_ENV = '+json.dumps(env)+';\n'+generated['google-apps-script/Build.gs']
        for name,content in source.items():bundle+='\n// MODULE '+name+'\n'+content+'\n'
        bundle+='\nif (CONFIG.environment !== BUNDLE_TARGET_ENV) throw new Error("BUNDLE_ENVIRONMENT_MISMATCH: configure DOMUS_ENV or choose the correct bundle.");\n'
        generated[f'google-apps-script/DOMUS_{env}_BUNDLE.gs']=bundle
    app=(ROOT/'js/app.js').read_text();index=(ROOT/'index.html').read_text();css=(ROOT/'css/app.css').read_text()
    native=re.sub(r'<link rel="stylesheet" href="css/app\.css[^\"]*"\s*/>',lambda _:'<style>'+css+'</style>',index)
    native=re.sub(r'<script src="js/app\.js[^\"]*"></script>',lambda _:'<script>'+app.replace('</script','<\\/script')+'</script>',native)
    native=native.replace('src="assets/','src="https://sadotechmx.github.io/Admin-Domus/assets/').replace('href="assets/','href="https://sadotechmx.github.io/Admin-Domus/assets/')
    generated['google-apps-script/Index.html']=native
    manifest={f'google-apps-script/{n}.gs':hashlib.sha256(v.encode()).hexdigest() for n,v in source.items()}
    manifest.update({'js/app.js':hashlib.sha256(app.encode()).hexdigest(),'index.html':hashlib.sha256(index.encode()).hexdigest()})
    manifest.update({name:hashlib.sha256(content.encode()).hexdigest() for name,content in generated.items()})
    generated['release-manifest.json']=json.dumps({'build':build_info,'files':manifest},indent=2)+'\n'
    for name,content in generated.items():
        file=ROOT/name
        if check:
            if not file.exists() or file.read_text()!=content:raise SystemExit('GENERATED FILE OUT OF DATE: '+name)
        else:file.write_text(content)
    print('PARITY VERIFIED' if check else 'GENERATED',len(generated),'files; source SHA256',digest)
if __name__=='__main__':build('--check' in sys.argv)
